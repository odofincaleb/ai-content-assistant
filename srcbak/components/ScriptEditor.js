// WordPress integration functionality
const generateWordPressContent = (content, options = {}) => {
  const {
    title = 'Generated Content',
    author = 'AI Content Assistant',
    category = 'General',
    tags = [],
    featuredImage = '',
    seoDescription = '',
    publishStatus = 'draft'
  } = options;
  
  // Convert content to WordPress-compatible format
  let wpContent = content;
  
  // Add WordPress-specific formatting
  if (featuredImage) {
    wpContent = `<!-- wp:image {"url":"${featuredImage}","id":1,"sizeSlug":"large"} -->
<figure class="wp-block-image size-large"><img src="${featuredImage}" alt="${title}"/></figure>
<!-- /wp:image -->

${wpContent}`;
  }
  
  // Create WordPress export object
  const wpExport = {
    title: title,
    content: wpContent,
    excerpt: seoDescription || content.substring(0, 160) + '...',
    author: author,
    categories: [category],
    tags: tags,
    status: publishStatus,
    date: new Date().toISOString(),
    featuredImage: featuredImage,
    seo: {
      title: title,
      description: seoDescription,
      keywords: tags.join(', ')
    }
  };
  
  return wpExport;
};

